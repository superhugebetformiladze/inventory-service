-- Выбытие машины из парка.
--
-- Контракт (docs/CONTRACT.md, §5) описывает выбытие как сообщение с
-- retired: true в уплотняемом топике, а не как удаление записи: потребитель,
-- читающий топик с начала, о молча удалённой машине никогда не узнал бы и
-- держал бы её в парке вечно.
--
-- Найдено живым разбором на десятом этапе. Тысяча машин нагрузочного прогона
-- была удалена из базы службы напрямую, и при первом же чтении ленты все
-- девятьсот девяносто пять приехали в очередь разбора учётной системы —
-- потому что в топике они остались, а надгробия им никто не отправил.
--
-- Отметка, а не удаление строки: снимки и изменения выбывшей машины остаются
-- на месте, и на вопрос «что стояло на списанном рабочем месте» можно
-- ответить и через год.
ALTER TABLE hosts ADD COLUMN retired_at timestamptz;

-- Выбывшие не участвуют ни в подсчёте парка, ни в поиске молчащих: списанная
-- машина молчит по определению, и тревога о ней — ложная.
CREATE INDEX hosts_active_idx ON hosts (last_report_at) WHERE retired_at IS NULL;

-- +goose Down
DROP INDEX IF EXISTS hosts_active_idx;
ALTER TABLE hosts DROP COLUMN retired_at;
