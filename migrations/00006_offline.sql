-- Нужно не для отчётности: у машин без сети «на связи» не двигается никогда,
-- и без этой пометки они выглядят как замолчавшие (см. hosts.silent_since).
ALTER TABLE agents ADD COLUMN enrolled_offline boolean NOT NULL DEFAULT false;

