-- Открытый ключ машины: им проверяется подпись отчёта, принесённого файлом.
--
-- Открытый — и в этом весь смысл. Служба и раньше хранила от машины только
-- хеш её ключа доступа, поэтому проверить подпись на общем секрете не могла
-- бы: пришлось бы держать ключи машин в открытом виде, и одна утечка базы
-- давала бы право писать в учёт от имени любой машины парка.
--
-- Открытый ключ не секрет: подделать им отчёт нельзя, и утечка не даёт
-- ничего. Закрытый остаётся на машине и никуда не уезжает.
ALTER TABLE agents ADD COLUMN public_key bytea;

