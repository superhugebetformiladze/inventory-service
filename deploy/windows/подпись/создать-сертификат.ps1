# Создание собственного сертификата подписи кода.
#
# Выполняется ОДИН РАЗ на машине администратора. Дальше этим сертификатом
# подписывается каждая сборка агента, а его открытая часть едет в пакете
# раскатки и ставится на рабочие станции как доверенная.
#
# Зачем это нужно. Неподписанный exe в корпоративной сети встречает
# SmartScreen, политики ограниченного запуска и антивирус, и каждая такая
# встреча заканчивается машиной, на которой агента нет, — молча.
#
# Почему самоподписанный. Коммерческий сертификат стоит 10-20 тыс. в год и
# нужен там, где программу запускают на чужих машинах. Здесь машины свои, и
# доверие к своему сертификату можно установить самому — тем же пакетом
# раскатки, которым ставится агент.
#
# ГЛАВНОЕ ПРЕДУПРЕЖДЕНИЕ. Закрытый ключ этого сертификата — это право
# подписать ЛЮБУЮ программу так, что весь парк сочтёт её доверенной. Файл
# .pfx нельзя класть в общую папку, в систему контроля версий или на сетевой
# диск. Его место — на одной машине администратора или в защищённом хранилище,
# и пароль к нему не должен совпадать ни с одним другим паролем.

$ErrorActionPreference = 'Stop'

$Название = 'Инвентаризация — подпись агента'
$Каталог = Join-Path $PSScriptRoot 'ключи'
$Годы = 5

# Пять лет, а не год: подпись с меткой времени продолжает считаться
# действительной и после истечения сертификата, а вот перевыпуск и повторная
# раскатка корневого сертификата по всему парку — работа, которую не хочется
# делать ежегодно.

if (-not (Test-Path $Каталог)) {
    New-Item -ItemType Directory $Каталог | Out-Null
}

$pfx = Join-Path $Каталог 'подпись.pfx'
$cer = Join-Path $Каталог 'подпись.cer'

if (Test-Path $pfx) {
    Write-Host "Сертификат уже создан: $pfx" -ForegroundColor Yellow
    Write-Host 'Создавать второй незачем: машины парка доверяют первому.'
    Write-Host 'Если он действительно потерян — удалите файлы в каталоге ключи и повторите,'
    Write-Host 'но тогда придётся заново раскатать открытую часть на все машины.'
    exit 1
}

Write-Host 'Придумайте пароль к закрытому ключу.'
Write-Host 'Он понадобится при каждой подписи сборки. Записать его нужно туда же,'
Write-Host 'где хранятся остальные пароли администратора, а не в этот каталог.'
$пароль = Read-Host -AsSecureString 'Пароль'

$сертификат = New-SelfSignedCertificate `
    -Type CodeSigningCert `
    -Subject "CN=$Название" `
    -KeyUsage DigitalSignature `
    -KeyLength 3072 `
    -KeyAlgorithm RSA `
    -HashAlgorithm SHA256 `
    -NotAfter (Get-Date).AddYears($Годы) `
    -CertStoreLocation 'Cert:\CurrentUser\My'

Export-PfxCertificate -Cert $сертификат -FilePath $pfx -Password $пароль | Out-Null
Export-Certificate  -Cert $сертификат -FilePath $cer | Out-Null

Write-Host ''
Write-Host 'Готово.' -ForegroundColor Green
Write-Host "  $pfx  — закрытый ключ. НИКУДА не копировать, никому не отдавать."
Write-Host "  $cer  — открытая часть. Её кладут в пакет раскатки."
Write-Host ''
Write-Host "Отпечаток: $($сертификат.Thumbprint)"
Write-Host 'По нему можно убедиться, что на рабочей станции стоит именно этот сертификат.'
