// Package contract описывает то, о чём договариваются агент, служба и все
// потребители ленты: снимок машины и события об изменениях.
//
// # Почему это отдельный публичный пакет
//
// Его импортируют три стороны сразу — агент, служба и любой Go-потребитель.
// Держать эти структуры внутри internal значило бы, что каждый потребитель
// перепишет их у себя, и однажды одна из копий разойдётся с остальными молча.
//
// # Правило совместимости (инвариант I5)
//
// Контракт меняется ТОЛЬКО добавлением полей. Удаление поля, переименование,
// смена типа или смысла — это новая версия топика и период, когда живут обе.
//
// Причина в том, что стороны обновляются не одновременно: агент на пятистах
// машинах доедет до новой версии за недели, а служба обновится сегодня. Всё
// это время старые агенты шлют старый снимок, а новые потребители читают
// ленту, где лежат сообщения обеих версий.
//
// Отсюда два следствия, обязательных для всех:
//
//   - Читатель ИГНОРИРУЕТ незнакомые поля, а не падает на них. Разбор с
//     DisallowUnknownFields в этом проекте запрещён.
//   - Писатель НЕ полагается на то, что читатель понял новое поле.
//
// # Единицы измерения — в имени поля
//
// SizeBytes, а не Size. TotalBytes, а не Total. Это не занудство: в учётной
// системе, откуда переносятся данные, объём дисков записан строками «1Тб»,
// «128 GB», «1.2Тб», «240 Gb (ssd)» — ровно потому, что единицу когда-то
// оставили на усмотрение заполняющего. Один раз договориться дешевле, чем
// потом разбирать 369 значений регулярным выражением.
//
// Время — всегда UTC.
